import type { GameEngineState } from '../engine';
import type { BuildingType, DroneStationMode } from '../types';

/** Serializable commands accepted by the authoritative game runtime. */
export type GameCommand =
  | { type: 'SET_INPUT_KEY'; code: string; pressed: boolean }
  | { type: 'AIM_AT'; worldX: number; worldY: number }
  | { type: 'POINTER_DOWN'; button: 0 | 2; worldX: number; worldY: number }
  | { type: 'POINTER_UP'; button: 0 | 2 }
  | { type: 'SELECT_BUILDING'; buildingType: BuildingType | null }
  | { type: 'CANCEL_SELECTION' }
  | { type: 'PLACE_SELECTED_BUILDING' }
  | { type: 'UPGRADE_NEARBY'; key: 'Q' | 'E' }
  | { type: 'REPAIR_NEARBY'; buildingId?: string }
  | { type: 'DISMANTLE_NEARBY'; buildingId?: string }
  | { type: 'TOGGLE_DRONE_MODE' }
  | { type: 'SET_DRONE_MODE'; stationId: string; mode: DroneStationMode }
  | { type: 'SET_GROUP_ALLIANCE'; groupId: string; allianceId: string }
  | { type: 'SET_GROUP_IDENTITY'; groupId: string; name: string; commanderName: string; color?: string }
  | { type: 'RESTART' };

/** Read-only-by-contract state emitted by the authoritative simulation. */
export type GameSnapshot = Readonly<GameEngineState>;
export type GameClientRole = 'controller' | 'observer';

export interface ConnectClientOptions {
  /** Current connection-session identity, generated by the active adapter when the client connects. */
  clientId?: string;
  /** Only one controller is allowed in single-player mode; extra clients are observers. */
  role?: GameClientRole;
}

export interface GameClientSessionInfo {
  readonly worldId: string;
  readonly clientId: string;
  readonly role: GameClientRole;
  /** Currently the single-player authority is bound to the only commander. Observers have none. */
  readonly controlledEntityId: string | null;
  readonly joinedAtRevision: number;
}

/** A versioned, transport-friendly wrapper around the state of one shared world. */
export interface GameWorldFrame {
  readonly protocolVersion: 3;
  readonly worldId: string;
  /** Stable unsigned seed used for procedural chunks and enemy-base placement. */
  readonly worldSeed: number;
  readonly revision: number;
  readonly serverTimeMs: number;
  readonly snapshot: GameSnapshot;
}

/** Envelope used by local and future remote clients; sequence numbers make retries/deduplication possible. */
export interface ClientCommandEnvelope {
  readonly protocolVersion: 1;
  readonly worldId: string;
  readonly clientId: string;
  readonly sequence: number;
  readonly observedRevision: number;
  readonly command: GameCommand;
}

export interface GameClientPort {
  readonly session: GameClientSessionInfo;
  getSnapshot(): GameSnapshot;
  /** Optional render-only interpolated/predicted view; authoritative reads remain getSnapshot(). */
  getRenderSnapshot?(): GameSnapshot;
  /** Input hints used only for local visual prediction; never grant gameplay authority. */
  setPredictedInputKey?(code: string, pressed: boolean): void;
  setPredictedAimPoint?(worldX: number, worldY: number): void;
  getWorldFrame(): GameWorldFrame;
  subscribe(listener: (snapshot: GameSnapshot) => void): () => void;
  subscribeWorldFrames(listener: (frame: GameWorldFrame) => void): () => void;
  /** Returns false if the session lacks authority or the command is rejected. */
  dispatch(command: GameCommand): boolean;
  disconnect(): void;
}

export interface GameServerPort {
  readonly worldId: string;
  getSnapshot(): GameSnapshot;
  getWorldFrame(): GameWorldFrame;
  subscribe(listener: (snapshot: GameSnapshot) => void): () => void;
  subscribeWorldFrames(listener: (frame: GameWorldFrame) => void): () => void;
  /** Server/system-side command hook. Browser clients should dispatch through a GameClientPort. */
  dispatch(command: GameCommand): void;
  connectClient(options?: ConnectClientOptions): GameClientPort;
  getConnectedClients(): readonly GameClientSessionInfo[];
  start(): void;
  stop(): void;
}


const BUILDING_TYPES = new Set<BuildingType>(['CORE', 'WALL', 'AUTO_TURRET', 'HARVESTER_STATION', 'DRONE_STATION', 'FIRE_TOWER']);
const isFiniteNumber = (value: unknown): value is number => typeof value === 'number' && Number.isFinite(value);
const isNonEmptyString = (value: unknown, max = 128): value is string => typeof value === 'string' && value.trim().length > 0 && value.length <= max;

/** Runtime schema guard shared by local and remote command adapters. */
export function isValidGameCommand(value: unknown): value is GameCommand {
  if (!value || typeof value !== 'object') return false;
  const command = value as Record<string, unknown>;
  switch (command.type) {
    case 'SET_INPUT_KEY': return isNonEmptyString(command.code, 32) && typeof command.pressed === 'boolean';
    case 'AIM_AT': return isFiniteNumber(command.worldX) && isFiniteNumber(command.worldY);
    case 'POINTER_DOWN': return (command.button === 0 || command.button === 2) && isFiniteNumber(command.worldX) && isFiniteNumber(command.worldY);
    case 'POINTER_UP': return command.button === 0 || command.button === 2;
    case 'SELECT_BUILDING': return command.buildingType === null || (typeof command.buildingType === 'string' && BUILDING_TYPES.has(command.buildingType as BuildingType));
    case 'CANCEL_SELECTION': case 'PLACE_SELECTED_BUILDING': case 'TOGGLE_DRONE_MODE': case 'RESTART': return true;
    case 'UPGRADE_NEARBY': return command.key === 'Q' || command.key === 'E';
    case 'REPAIR_NEARBY': case 'DISMANTLE_NEARBY': return command.buildingId === undefined || isNonEmptyString(command.buildingId);
    case 'SET_DRONE_MODE': return isNonEmptyString(command.stationId) && (command.mode === 'DEFENSE' || command.mode === 'ESCORT');
    case 'SET_GROUP_ALLIANCE': return isNonEmptyString(command.groupId) && isNonEmptyString(command.allianceId);
    case 'SET_GROUP_IDENTITY': return isNonEmptyString(command.groupId) && isNonEmptyString(command.name, 64) && isNonEmptyString(command.commanderName, 64) && (command.color === undefined || (typeof command.color === 'string' && /^#[0-9a-fA-F]{6}$/.test(command.color)));
    default: return false;
  }
}
