import type { Building, BuildingType, DroneStationMode, EnemyBase, GameEntity, Projectile, ResourceNode, Resources } from '../types';
import type { EngineHumanPlayer, GameEngineState } from './model';
import type { PrioritizedCombatTarget } from '../combat';

export abstract class EngineContract {
  protected abstract createInitialState(): GameEngineState;
  public abstract setMultiplayerMode(mode: GameEngineState['multiplayerMode']): void;
  public abstract prepareWorldStart(): void;
  protected abstract isResourceCellOccupied(gx: number, gy: number): boolean;
  public abstract addHumanParticipant(playerId: string, mode?: GameEngineState['multiplayerMode']): EngineHumanPlayer;
  public abstract setHumanParticipantConnected(playerId: string, connected: boolean): boolean;
  public abstract setHumanParticipantDisplayName(playerId: string, displayName: string): boolean;
  public abstract reviveHumanParticipant(playerId: string): boolean;
  public abstract removeHumanParticipant(playerId: string): boolean;
  public abstract dispatchForPlayer(playerId: string, command: { type: string; [key: string]: unknown }, execute: () => void): boolean;
  public abstract setPlayerInputKey(playerId: string, code: string, pressed: boolean): boolean;
  public abstract setPlayerAimPoint(playerId: string, worldX: number, worldY: number): boolean;
  public abstract setOnStateChange(callback: (state: GameEngineState) => void): any;
  protected abstract initWorld(): any;
  protected abstract loadChunk(cx: number, cy: number): any;
  protected abstract loadChunksAroundWorld(worldX: number, worldY: number, radius: number): any;
  protected abstract updateChunks(): any;
  public abstract setInputKey(code: string, pressed: boolean): any;
  public abstract setAimPoint(worldX: number, worldY: number): any;
  public abstract handleWorldPointerDown(button: 0 | 2, worldX: number, worldY: number): any;
  public abstract handleWorldPointerUp(button: 0 | 2): any;
  public abstract cancelSelection(): any;
  public abstract selectBuilding(type: BuildingType | null): any;
  protected abstract canUsePlayerStructure(building: Building): boolean;
  public abstract setDroneStationMode(stationId: string, mode: DroneStationMode): any;
  public abstract attemptToggleDroneMode(): any;
  public abstract attemptPlaceSelectedBuilding(): any;
  public abstract attemptRepairNearby(buildingId?: string): any;
  protected abstract getNearbyUpgradeTarget(): any;
  public abstract attemptUpgradeHotkeyNearby(key: 'Q' | 'E'): any;
  public abstract attemptUpgradeNearby(buildingId?: string, upgradeId?: string): any;
  public abstract attemptDismantleNearby(buildingId?: string): any;
  public abstract setGroupAlliance(groupId: string, allianceId: string): boolean;
  public abstract setGroupIdentity(groupId: string, name: string, commanderName: string, color?: string): boolean;
  public abstract step(dt: number): any;
  protected abstract setActivePlayerResources(resources: Resources): void;
  public abstract triggerStateChange(): any;
  protected abstract update(dt: number): any;
  protected abstract updatePlayer(dt: number): any;
  protected abstract isParticipantDefeated(playerId: string): boolean;
  protected abstract retireDefeatedParticipant(participant: EngineHumanPlayer): void;
  protected abstract updateSinglePlayer(dt: number): any;
  protected abstract firePlayerWeapon(): any;
  protected abstract updateAutonomousUnits(dt: number): any;
  protected abstract updateBuildings(dt: number): any;
  public abstract resolveCachedBuildingTarget(building: Building, entities: GameEntity[], buildings: Building[], range: number): PrioritizedCombatTarget | undefined;
  protected abstract updateEnemyBases(dt: number): any;
  public abstract damageBuilding(target: Building, rawDamage: number, source?: Pick<Building, 'faction' | 'teamId' | 'allianceId' | 'ownerPlayerId'>
      | Pick<Projectile, 'faction' | 'teamId' | 'allianceId' | 'ownerPlayerId'>): any;
  protected abstract awardDiamondForCore(core: Building, source: Pick<Building, 'faction' | 'teamId' | 'allianceId' | 'ownerPlayerId'>
      | Pick<Projectile, 'faction' | 'teamId' | 'allianceId' | 'ownerPlayerId'>): void;
  protected abstract steerGuidedProjectile(projectile: Projectile, dt: number): void;
  protected abstract projectileCanReachTarget(projectile: Projectile, targetX: number, targetY: number): boolean;
  protected abstract tryReflectProjectile(projectile: Projectile, wall: Building): boolean;
  protected abstract applyProjectileExplosion(projectile: Projectile, x: number, y: number, directTargetId: string): void;
  protected abstract updateProjectiles(dt: number): any;
  protected abstract updateParticles(dt: number): any;
  protected abstract updateFloatingTexts(dt: number): any;
  public abstract addFloatingText(x: number, y: number, text: string, color: string): any;
  public abstract createSparks(x: number, y: number, color: string, count?: number, particleSize?: any): any;
  public abstract canRestartGame(): boolean;
  public abstract configureLobbyMode(mode: GameEngineState['multiplayerMode']): void;
  public abstract restartGame(): boolean;
}
